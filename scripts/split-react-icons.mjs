/* Split react-icons into one small file per icon (production builds only).
 *
 * Why: each react-icons set (e.g. "react-icons/ri") is a single file holding
 * thousands of icons. Webpack can only tree-shake it once for the whole site,
 * so every page shipped every Ri icon used *anywhere* in the app (~32 KB
 * gzipped). With one file per icon, each page only downloads the icons it
 * actually shows. The icons render exactly the same — the SVG data is copied
 * verbatim from react-icons.
 *
 * How: during `next build`, next.config.mjs calls this once. It scans src/
 * for `import { ... } from "react-icons/<set>"` and copies those icons into
 * .react-icons-split/<set>/<Icon>.js; react-icons-split-loader.cjs then
 * points the imports at those files. Nothing to run by hand: the folder is
 * regenerated on every build and can be git-ignored. `next dev` keeps using
 * react-icons directly, so new icons work immediately while developing.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const IMPORT_RE = /import\s*\{([^}]*)\}\s*from\s*["']react-icons\/(\w+)["']/g;
const SOURCE_EXT = /\.(jsx?|mjs|tsx?)$/;

function walk(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full, out);
        else if (SOURCE_EXT.test(entry.name)) out.push(full);
    }
    return out;
}

function findUsedIcons(srcDir) {
    const used = new Map(); // set -> Set(names)
    for (const file of walk(srcDir)) {
        const code = fs.readFileSync(file, "utf8");
        for (const match of code.matchAll(IMPORT_RE)) {
            const set = match[2];
            const names = match[1]
                .split(",")
                .map((n) => n.trim().split(/\s+as\s+/)[0].trim())
                .filter(Boolean);
            if (!used.has(set)) used.set(set, new Set());
            names.forEach((n) => used.get(set).add(n));
        }
    }
    return used;
}

/** Returns { sets: [...], outDir } — the sets that were split. */
export function splitReactIcons(projectRoot) {
    const require = createRequire(path.join(projectRoot, "package.json"));
    const iconsRoot = path.join(path.dirname(require.resolve("react-icons/lib")), "..");
    const outDir = path.join(projectRoot, ".react-icons-split");
    const used = findUsedIcons(path.join(projectRoot, "src"));

    fs.rmSync(outDir, { recursive: true, force: true });

    const sets = [];
    for (const [set, names] of used) {
        let source;
        try {
            source = fs.readFileSync(path.join(iconsRoot, set, "index.mjs"), "utf8");
        } catch {
            continue; // unknown set — leave its imports untouched
        }

        const bodies = new Map();
        for (const m of source.matchAll(/export function (\w+) \(props\) \{\n\s*return (GenIcon\([\s\S]*?\)\(props\));\n\};/g)) {
            if (names.has(m[1])) bodies.set(m[1], m[2]);
        }

        const missing = [...names].filter((n) => !bodies.has(n));
        if (missing.length) {
            // Don't split a set we can't fully resolve; webpack will report
            // a genuinely misspelt icon name exactly as before.
            console.warn(`[split-react-icons] react-icons/${set}: not splitting (unresolved: ${missing.join(", ")})`);
            continue;
        }

        const setDir = path.join(outDir, set);
        fs.mkdirSync(setDir, { recursive: true });
        for (const [name, body] of bodies) {
            fs.writeFileSync(
                path.join(setDir, `${name}.js`),
                `// Generated by scripts/split-react-icons.mjs from react-icons/${set}. Do not edit.\n` +
                    `import { GenIcon } from "react-icons/lib";\n` +
                    `export default function ${name}(props) {\n  return ${body};\n}\n` +
                    `export { ${name} };\n`
            );
        }
        sets.push(set);
    }

    return { sets, outDir };
}
